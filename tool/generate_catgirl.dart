import 'dart:io';

const _sourcePath = 'lib/l10n/l10n.dart';
const _outputPath = 'lib/common/generated/catgirl_localizations.g.dart';
const _mixinName = 'CatgirlLocalizationOverrides';

final _getterPattern = RegExp(r'^  String get ([A-Za-z_][A-Za-z0-9_]*) *[{=]');
final _methodPattern = RegExp(
  r'^  String ([A-Za-z_][A-Za-z0-9_]*)\(([^)]*)\) *[{=]',
);
final _parameterPattern = RegExp(r'([A-Za-z_][A-Za-z0-9_]*)\s*(?:=.*)?$');

Future<void> main() async {
  final root = _repoRoot();
  final source = File(_join(root, _sourcePath));
  if (!source.existsSync()) {
    _fail('Cannot find $source. Run this script from the repository root.');
  }
  final lines = source.readAsStringSync().split('\n');
  final classStart = lines.indexWhere(
    (line) => line.trim() == 'class AppLocalizations {',
  );
  if (classStart < 0) {
    _fail('Cannot find class AppLocalizations in $source.');
  }
  final classEnd = lines.indexWhere((line) => line == '}', classStart + 1);
  if (classEnd < 0) {
    _fail('Cannot find the end of class AppLocalizations in $source.');
  }
  var getters = 0;
  var methods = 0;
  final overrides = <String>[];
  for (final line in lines.sublist(classStart + 1, classEnd)) {
    final getter = _getterPattern.firstMatch(line);
    if (getter != null) {
      final name = getter[1]!;
      overrides.add(
        '  @override\n'
        '  String get $name => catgirlize(base.$name, localeName);\n',
      );
      getters++;
      continue;
    }
    final method = _methodPattern.firstMatch(line);
    if (method != null) {
      final name = method[1]!;
      final signature = method[2]!.trim();
      final arguments = _argumentNames(name, signature);
      overrides.add(
        '  @override\n'
        '  String $name($signature) => '
        'catgirlize(base.$name($arguments), localeName);\n',
      );
      methods++;
      continue;
    }
    if (line.startsWith('  String ')) {
      _fail('Unsupported declaration, update the generator: $line');
    }
  }
  if (overrides.isEmpty) {
    _fail('No AppLocalizations accessors found in $source.');
  }
  final output = File(_join(root, _outputPath));
  output.parent.createSync(recursive: true);
  output.writeAsStringSync(
    '// GENERATED CODE - DO NOT MODIFY BY HAND\n'
    '// Generated by tool/generate_catgirl.dart from $_sourcePath.\n'
    '\n'
    "import 'package:fl_clash/common/catgirl_text.dart';\n"
    "import 'package:fl_clash/l10n/l10n.dart';\n"
    '\n'
    '/// Overrides every [AppLocalizations] accessor through [catgirlize].\n'
    'mixin $_mixinName on AppLocalizations {\n'
    '  /// The localizations every override reads from.\n'
    '  AppLocalizations get base;\n'
    '\n'
    '  /// Canonicalized locale of [base].\n'
    '  String get localeName;\n'
    '\n'
    '${overrides.join('\n')}'
    '}\n',
  );
  final format = await Process.run(Platform.resolvedExecutable, [
    'format',
    output.path,
  ]);
  if (format.exitCode != 0) {
    stderr.write(format.stderr);
    exit(1);
  }
  stdout.writeln(
    'Wrote $getters getters and $methods methods to $_outputPath.',
  );
}

String _argumentNames(String method, String signature) {
  if (signature.isEmpty) return '';
  if (signature.contains('{') || signature.contains('[')) {
    _fail('Optional parameters are not supported ($method).');
  }
  return signature
      .split(',')
      .map((parameter) {
        final match = _parameterPattern.firstMatch(parameter.trim());
        if (match == null) {
          _fail('Cannot read parameter "$parameter" of $method.');
        }
        return match[1]!;
      })
      .join(', ');
}

Directory _repoRoot() {
  final fromCwd = File(_sourcePath);
  if (fromCwd.existsSync()) return Directory.current;
  final script = File.fromUri(Platform.script);
  if (script.existsSync()) return script.parent.parent;
  _fail('Cannot locate the repository root.');
}

Never _fail(String message) {
  stderr.writeln(message);
  exit(1);
}

String _join(Directory root, String relative) =>
    '${root.path}${Platform.pathSeparator}'
    '${relative.replaceAll('/', Platform.pathSeparator)}';
